#!/bin/sh
# One-command Jenkins + SonarQube lab for this repository (LOCAL USE ONLY).
#
#   sh deploy/local/ci/lab.sh up      # generate secrets, start, configure, report
#   sh deploy/local/ci/lab.sh status  # URLs and logins
#   sh deploy/local/ci/lab.sh run     # trigger the bookstore pipeline
#   sh deploy/local/ci/lab.sh down    # stop containers (keeps data)
#   sh deploy/local/ci/lab.sh reset   # stop and DELETE all lab CI data
set -eu

ci_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
root=$(CDPATH= cd -- "$ci_dir/../../.." && pwd)
cd "$ci_dir"
env_file=.env
secrets=../.secrets/lab.env
action=${1:-up}

lab_info() { printf '==> %s\n' "$*"; }
lab_die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# Precedence: explicit DOCKER_GID, then the socket's group, then the login
# group (Docker Desktop on macOS often exposes the socket with a mapped group).
detect_docker_gid() {
  if [ -n "${DOCKER_GID:-}" ]; then
    echo "$DOCKER_GID"
    return 0
  fi
  socket=/var/run/docker.sock
  if [ -S "$socket" ] && command -v stat >/dev/null 2>&1; then
    detected=$(stat -c %g "$socket" 2>/dev/null || stat -f %g "$socket" 2>/dev/null || true)
    if [ -n "$detected" ]; then
      echo "$detected"
      return 0
    fi
  fi
  if command -v id >/dev/null 2>&1; then
    echo "warning: could not read the Docker socket group; using login group $(id -g)" >&2
    id -g
  fi
}

# .env is generated once and reused: regenerating it would break the running
# SonarQube database and Jenkins credentials.
ensure_env() {
  if [ ! -f "$env_file" ]; then
    gid=$(detect_docker_gid)
    [ -n "${gid:-}" ] || lab_die 'Could not determine the Docker socket group. Re-run with DOCKER_GID=<group id>.'
    python3 "$root/scripts/lab-secrets.py" ensure --file "$secrets" \
      JENKINS_ADMIN_PASSWORD SONAR_DB_PASSWORD SONAR_ADMIN_PASSWORD >/dev/null
    umask 077
    {
      echo "# Generated by deploy/local/ci/lab.sh - do not commit."
      echo "DOCKER_GID=$gid"
      echo "JENKINS_BRANCH=$(git -C "$root" rev-parse --abbrev-ref HEAD)"
      echo "JENKINS_REPO_URL=$(git -C "$root" remote get-url origin 2>/dev/null || echo https://github.com/An619/bookstore-3tier.git)"
      echo "JENKINS_ADMIN_PASSWORD=$(python3 "$root/scripts/lab-secrets.py" get --file "$secrets" --key JENKINS_ADMIN_PASSWORD)"
      echo "SONAR_DB_PASSWORD=$(python3 "$root/scripts/lab-secrets.py" get --file "$secrets" --key SONAR_DB_PASSWORD)"
      echo "SONAR_ADMIN_PASSWORD=$(python3 "$root/scripts/lab-secrets.py" get --file "$secrets" --key SONAR_ADMIN_PASSWORD)"
    } > "$env_file"
    chmod 600 "$env_file"
    lab_info "Generated $ci_dir/$env_file"
  fi
  # shellcheck disable=SC1090
  . "./$env_file"
  export DOCKER_GID JENKINS_ADMIN_PASSWORD SONAR_DB_PASSWORD SONAR_ADMIN_PASSWORD
  if [ -n "${SONAR_TOKEN:-}" ]; then export SONAR_TOKEN; fi
}

set_env_value() {
  key=$1 value=$2
  python3 - "$env_file" "$key" "$value" <<'PY'
import sys
from pathlib import Path
path, key, value = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
lines = [line for line in path.read_text().splitlines() if not line.startswith(key + '=')]
lines.append(f'{key}={value}')
path.write_text('\n'.join(lines) + '\n')
PY
  chmod 600 "$env_file"
}

wait_http() {
  url=$1 label=$2 attempts=${3:-60}
  attempt=1
  while [ "$attempt" -le "$attempts" ]; do
    if curl -fsS --max-time 5 "$url" >/dev/null 2>&1; then
      return 0
    fi
    attempt=$((attempt + 1))
    sleep 5
  done
  lab_die "$label did not become ready. Inspect: docker compose -f $ci_dir/docker-compose.yml logs"
}

prepare_sonarqube() {
  lab_info 'Starting SonarQube (first boot takes a couple of minutes)'
  docker compose up -d sonar-db sonarqube
  wait_http http://localhost:9000/api/system/status SonarQube 60
  if [ -z "${SONAR_TOKEN:-}" ]; then
    lab_info 'Configuring SonarQube project, quality gate and token'
    token=$(python3 "$root/scripts/sonar-bootstrap.py" \
      --url http://localhost:9000 --admin-password "$SONAR_ADMIN_PASSWORD")
    [ -n "$token" ] || lab_die 'SonarQube token generation failed'
    set_env_value SONAR_TOKEN "$token"
    SONAR_TOKEN=$token
    export SONAR_TOKEN
  else
    lab_info 'Reusing the existing SonarQube token from .env'
  fi
}

prepare_jenkins() {
  lab_info 'Starting Jenkins with configuration-as-code'
  docker compose up -d --build jenkins
  wait_http http://localhost:8085/login Jenkins 90
}

summary() {
  cat <<TEXT

Jenkins    http://localhost:8085   user: admin
           password: see deploy/local/ci/lab.sh status
SonarQube  http://localhost:9000   user: admin
Quality gate "Bookstore lab gate" (new-code coverage) is assigned to project
bookstore-3tier, and its token is already stored in Jenkins as sonarqube-token.

Pipeline job "bookstore-pipeline" was created on first boot. Trigger it with:
  sh deploy/local/ci/lab.sh run

The pipeline publishes its Compose stack on ports 18080-18083, so it can run
while the kind application lab keeps port 8080.
TEXT
}

case "$action" in
  up)
    command -v docker >/dev/null 2>&1 || lab_die 'Docker is required.'
    docker info >/dev/null 2>&1 || lab_die 'The Docker daemon is not reachable.'
    docker compose version >/dev/null 2>&1 || lab_die 'Docker Compose v2 is required.'
    . "$root/scripts/lab-tools.sh"
    lab_check_sonar_kernel
    ensure_env
    prepare_sonarqube
    prepare_jenkins
    summary
    ;;
  status)
    ensure_env
    echo "Jenkins:   http://localhost:8085 (admin / $JENKINS_ADMIN_PASSWORD)"
    echo "SonarQube: http://localhost:9000 (admin / $SONAR_ADMIN_PASSWORD)"
    docker compose ps
    ;;
  run)
    ensure_env
    wait_http http://localhost:8085/login Jenkins 30
    code=$(curl -s -o /dev/null -w '%{http_code}' -u "admin:$JENKINS_ADMIN_PASSWORD" \
      -X POST http://localhost:8085/job/bookstore-pipeline/build)
    case "$code" in
      201) lab_info 'Pipeline queued: http://localhost:8085/job/bookstore-pipeline/' ;;
      404) lab_die 'Job bookstore-pipeline not found. Check Jenkins: http://localhost:8085' ;;
      403) lab_die 'Trigger was rejected. Open Jenkins and start the job manually.' ;;
      *) lab_die "Unexpected Jenkins response: HTTP $code" ;;
    esac
    ;;
  down)
    docker compose down
    ;;
  reset)
    docker compose down -v
    rm -f "$env_file"
    lab_info 'Removed containers, volumes and .env'
    ;;
  *)
    lab_die "Unknown action '$action'. Use: up | status | run | down | reset"
    ;;
esac
